CREATE TABLE IF NOT EXISTS `resume_market_listing` (
    `id` BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
    `resume_id` BIGINT NOT NULL COMMENT '发布源简历 ID',
    `seller_user_id` BIGINT NOT NULL COMMENT '作者用户 ID',
    `slug` VARCHAR(128) NOT NULL COMMENT '公开访问标识',
    `summary` VARCHAR(512) NOT NULL DEFAULT '' COMMENT '公开摘要',
    `tags` JSON NULL COMMENT '公开标签数组',
    `access_type` VARCHAR(16) NOT NULL COMMENT '访问类型: FREE/PAID',
    `price_cents` INT NOT NULL DEFAULT 0 COMMENT '单次永久解锁价格，单位分',
    `publication_status` VARCHAR(16) NOT NULL DEFAULT 'UNPUBLISHED' COMMENT '作者发布状态: PUBLISHED/UNPUBLISHED',
    `moderation_status` VARCHAR(16) NOT NULL DEFAULT 'APPROVED' COMMENT '平台审核状态: APPROVED/SUSPENDED',
    `moderated_by` BIGINT NULL COMMENT '最后审核管理员 ID',
    `moderated_at` DATETIME NULL COMMENT '最后审核时间',
    `moderation_reason` VARCHAR(255) NULL COMMENT '审核或暂停原因',
    `current_revision_id` BIGINT NULL COMMENT '当前公开快照版本 ID',
    `public_consent_at` DATETIME NULL COMMENT '作者确认公开隐私风险的时间',
    `published_at` DATETIME NULL COMMENT '首次发布时间',
    `version` INT NOT NULL DEFAULT 0 COMMENT '乐观版本号',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_market_listing_resume` (`resume_id`),
    UNIQUE KEY `uk_market_listing_slug` (`slug`),
    KEY `idx_market_listing_seller` (`seller_user_id`, `updated_at`),
    KEY `idx_market_listing_public` (`publication_status`, `moderation_status`, `updated_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='用户公开简历市场条目';

CREATE TABLE IF NOT EXISTS `resume_market_listing_revision` (
