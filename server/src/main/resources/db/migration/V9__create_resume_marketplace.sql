    `listing_id` BIGINT NOT NULL COMMENT '市场条目 ID',
    `revision_no` INT NOT NULL COMMENT '条目内递增版本号',
    `title_snapshot` VARCHAR(128) NOT NULL COMMENT '简历标题快照',
